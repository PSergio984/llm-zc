"""
04-search-evaluation.py — Evaluate search performance using ground truth data.

What this script does:
  We have a ground-truth dataset: questions paired with the ID of the document
  that contains the correct answer.  For each question, we run text search and
  check whether the correct document appears in the top-5 results.  The output
  is a "relevance list" per query (e.g., [1, 0, 0, 0, 0]) that downstream
  metrics (hit-rate, MRR) consume.

Why this matters:
  Without ground truth, we cannot measure search quality.  With relevance lists
  we can compute standard IR metrics and compare different search strategies
  (text, vector, hybrid) on equal footing.

Pipeline:
  1. Load ground truth CSV (generated by 03-ground-truth-batch.py)
  2. Load FAQ documents and build a minsearch index
  3. Define text_search(query) — the retrieval function to evaluate
  4. Compute relevance lists for every ground-truth query
  5. Results are ready for metric computation (lesson 05)

Design principle — generic search_function parameter:
  compute_relevance(q, search_function) accepts any callable that takes a
  query and returns ranked results.  We start with text_search, but later
  we can swap in vector_search, hybrid_search, or any other retriever without
  changing the evaluation logic.

Follows the llm-zoomcamp lesson "Search Evaluation":
  https://github.com/DataTalksClub/llm-zoomcamp/blob/main/04-evaluation/lessons/04-search-evaluation.md

Usage:
  python 04-evaluation/lessons/04-search-evaluation.py
"""

import pandas as pd
from tqdm.auto import tqdm

from ingest import load_faq_data, build_index

# ── 1. Load ground truth ─────────────────────────────────────────────────
# The CSV has two columns: 'question' (the query) and 'document' (the ID of
# the FAQ record that should be retrieved).
# If the file doesn't exist, we offer to download it from the course repo.

import os

ground_truth_path = "data/ground_truth-new.csv"
if not os.path.exists(ground_truth_path):
    import urllib.request
    print("Ground truth file not found locally. Downloading from course repo...")
    os.makedirs("data", exist_ok=True)
    url = ("https://raw.githubusercontent.com/DataTalksClub/"
           "llm-zoomcamp/main/04-evaluation/data/ground_truth-new.csv")
    urllib.request.urlretrieve(url, ground_truth_path)
    print(f"Downloaded to {ground_truth_path}")

df_ground_truth = pd.read_csv(ground_truth_path)
ground_truth = df_ground_truth.to_dict(orient="records")

print(f"Loaded {len(ground_truth)} ground truth records")

# ── 2. Load FAQ documents and build search index ─────────────────────────
# We use the same minsearch Index from ingest.py.  Only llm-zoomcamp docs
# are kept (matching the ground-truth filter used in lesson 03).

documents = load_faq_data()

# Filter to llm-zoomcamp only (aligns with ground truth generation)
documents_llm = [doc for doc in documents if doc["course"] == "llm-zoomcamp"]
documents = documents_llm

print(f"Loaded {len(documents)} llm-zoomcamp documents")

# Build in-memory minsearch index over text fields
index = build_index(documents)

# ── 3. Define the text search function ───────────────────────────────────
# The boost_dict weights the 'question' field higher than 'section' because
# a match in the question is more relevant than a match in the section name.
#
# Why name it text_search?
#   The name distinguishes it from vector_search or hybrid_search that we
#   may evaluate later.  Everything downstream takes a search_function
#   parameter, so we can swap implementations at the call site.

def text_search(query):
    """Run keyword search over the FAQ index.

    Args:
        query: Natural-language query string.

    Returns:
        List of result dicts with 'id', 'question', 'answer', etc.
    """
    boost_dict = {"question": 3.0, "section": 0.5}

    return index.search(
        query,
        num_results=5,
        boost_dict=boost_dict,
    )

# ── 4. Compute relevance for a single query ──────────────────────────────
# Relevance is binary: 1 if the retrieved document ID matches the ground-truth
# document ID, 0 otherwise.  This gives us a list of 5 values (one per result).
#
# Why generic search_function?
#   compute_relevance doesn't care which retriever we use — text, vector, or
#   hybrid.  The same function works for all of them because it only compares
#   IDs.  This mirrors how RAG works: the retrieval step is a pluggable
#   interface.

def compute_relevance(q, search_function):
    """Compute relevance list for one ground-truth record.

    Args:
        q: Dict with 'question' and 'document' keys.
        search_function: Callable(query) returning ranked result dicts.

    Returns:
        List of 5 binary ints: 1 = correct doc, 0 = wrong doc.
    """
    doc_id = q["document"]
    results = search_function(query=q["question"])

    relevance = []
    for d in results:
        relevance.append(int(d["id"] == doc_id))

    return relevance

# ── 5. Compute relevance for all queries ─────────────────────────────────
# Loops over every ground-truth record, calls compute_relevance, and collects
# the relevance lists.  The result is a 2D list where each row corresponds
# to one query and each column to a rank position.

def compute_relevance_total(ground_truth, search_function):
    """Compute relevance lists for every ground-truth record.

    Args:
        ground_truth: List of dicts with 'question' and 'document'.
        search_function: Callable(query) returning ranked result dicts.

    Returns:
        List of lists: relevance_total[i][j] = relevance at rank j for query i.
    """
    relevance_total = []

    for q in tqdm(ground_truth):
        relevance = compute_relevance(q, search_function)
        relevance_total.append(relevance)

    return relevance_total

# ── 6. Run on a sample first (smoke test) ────────────────────────────────
# Before committing to the full dataset, verify the logic works on 15 queries.

print("\n--- Sample: first 15 ground truth records ---")

ground_truth_sample = ground_truth[:15]
relevance_total_sample = compute_relevance_total(ground_truth_sample, text_search)

print("\nRelevance lists (sample):")
for i, rel in enumerate(relevance_total_sample):
    print(f"  [{i:2d}] {rel}")

# Count how many queries had the correct doc at rank 1
hit_rate_sample = sum(rel[0] == 1 for rel in relevance_total_sample) / len(relevance_total_sample)
print(f"\nSample hit-rate (correct doc at rank 1): {hit_rate_sample:.0%}")

# ── 7. Run on all ground truth records ───────────────────────────────────
# This produces the full relevance dataset consumed by lesson 05 metrics.

print(f"\n--- Full evaluation: all {len(ground_truth)} records ---")

relevance_total = compute_relevance_total(ground_truth, text_search)

print(f"\nComputed {len(relevance_total)} relevance lists")

# Quick aggregate stats
total_hits = sum(rel[0] == 1 for rel in relevance_total)
hit_rate = total_hits / len(relevance_total)
print(f"Correct doc at rank 1: {total_hits}/{len(relevance_total)} ({hit_rate:.0%})")

# Count how many queries found the correct doc anywhere in top-5
found_anywhere = sum(any(r == 1 for r in rel) for rel in relevance_total)
recall_at_5 = found_anywhere / len(relevance_total)
print(f"Correct doc in top-5: {found_anywhere}/{len(relevance_total)} ({recall_at_5:.0%})")

print("\nRelevance data ready for metric computation (lesson 05).")
